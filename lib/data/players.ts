import type { Player, PlayerTag } from "@/lib/types/player";

const zeroProgress = {
  level: 0,
  xp: 0,
  ratings: {
    batting: 0,
    bowling: 0,
    fielding: 0
  },
  stats: {
    matches: 0,
    runs: 0,
    wickets: 0,
    catches: 0
  }
} satisfies Pick<Player, "level" | "xp" | "ratings" | "stats">;

type PlayerSeed = Omit<Player, "level" | "xp" | "ratings" | "stats" | "avatar"> & {
  avatar?: string;
};

function makePlayer(player: PlayerSeed): Player {
  return {
    ...player,
    avatar: player.avatar ?? "",
    level: zeroProgress.level,
    xp: zeroProgress.xp,
    ratings: { ...zeroProgress.ratings },
    stats: { ...zeroProgress.stats }
  };
}

